"""Packs specs/ and data/ into js/bundle.js so the page also works when index.html
is opened straight from disk (file://), where browsers block fetching local files.
Re-run after editing any spec or data file: python scripts/build_bundle.py"""
import json, os, glob
root = os.path.join(os.path.dirname(__file__), "..")
specs = {os.path.basename(p)[:-8]: json.load(open(p, encoding="utf-8")) for p in sorted(glob.glob(f"{root}/specs/*.vl.json"))}
data = {"data/" + os.path.basename(p): open(p, encoding="utf-8").read() for p in sorted(glob.glob(f"{root}/data/*"))}
with open(f"{root}/js/bundle.js", "w", encoding="utf-8") as f:
    f.write("// Auto-generated by scripts/build_bundle.py - offline copy of specs/ and data/\n")
    f.write("window.DV2_SPECS = " + json.dumps(specs, ensure_ascii=False) + ";\n")
    f.write("window.DV2_DATA = " + json.dumps(data, ensure_ascii=False) + ";\n")
print(len(specs), "specs,", len(data), "data files bundled")
